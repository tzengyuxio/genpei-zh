    g = Guide(data)
    pages = {"scenarios.md": g.scenarios(), "generals.md": g.generals(),
             "bases.md": g.bases(), "treasures.md": g.treasures_page(),
             "ranks.md": g.ranks_page(), "tables.md": g.index()}
    for name, text in pages.items():
        (out / name).write_text(text, encoding="utf-8")
        print(f"{out / name}: {text.count(chr(10))} lines")


